/// `3 characters`.
pub(crate) fn character_count(count: usize) -> String {
    if count == 1 {
        "1 character".to_owned()
    } else {
        format!("{count} characters")
    }
}

/// `3 outfits`.
pub(crate) fn costume_count(count: usize) -> String {
    if count == 1 {
        "1 outfit".to_owned()
    } else {
        format!("{count} outfits")
    }
}

/// `3 packages`.
pub(crate) fn package_count(count: usize) -> String {
    if count == 1 {
        "1 package".to_owned()
    } else {
        format!("{count} packages")
    }
}

/// A download row for an installed package: `Installed · 3 outfits · 12.0 MB`.
pub(crate) fn installed_row(costumes: usize, size: &str) -> String {
    format!("Installed · {} · {size}", costume_count(costumes))
}
