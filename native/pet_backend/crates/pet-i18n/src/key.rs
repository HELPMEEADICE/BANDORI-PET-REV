//! Every translatable UI string, in catalogue order.
//!
//! The list is generated from the translation table; each language table must
//! cover every variant, so a missing translation fails to compile instead of
//! silently falling back to another language.

macro_rules! keys {
    ($($variant:ident),* $(,)?) => {
        /// One translatable string.
        #[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord)]
        pub enum Key {
            $(
                #[allow(missing_docs)]
                $variant,
            )*
        }

        impl Key {
            /// Every key, in catalogue order.
            pub const ALL: &'static [Key] = &[$(Key::$variant),*];

            /// Stable identifier used by tests and translator tooling.
            pub fn name(self) -> &'static str {
                match self {
                    $(Key::$variant => stringify!($variant)),*
                }
            }
        }
    };
}

