/// `3 位角色`.
pub(crate) fn character_count(count: usize) -> String {
    format!("{count} 位角色")
}

/// `3 套服裝`.
pub(crate) fn costume_count(count: usize) -> String {
    format!("{count} 套服裝")
}

/// `3 個模型包`.
pub(crate) fn package_count(count: usize) -> String {
    format!("{count} 個模型包")
}

/// A download row for an installed package: `已安裝 · 3 套服裝 · 12.0 MB`.
pub(crate) fn installed_row(costumes: usize, size: &str) -> String {
    format!("已安裝 · {} · {size}", costume_count(costumes))
}
